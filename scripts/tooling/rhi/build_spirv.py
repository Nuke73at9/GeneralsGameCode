#!/usr/bin/env python3
# Tiberium Project @feature Compiles HLSL to SPIR-V with DXC for the RHI's Vulkan device and writes each
# result as a C++ header (an array of 32-bit words), so the build needs no shader compiler.
#
# Usage:
#   build_spirv.py --dxc <dxc> [--spirv-val <spirv-val>] <manifest> <output dir>
#
# The manifest lists one shader per line, relative to the manifest's folder:
#   <source.hlsl> <profile> <entry> <symbol>
# Blank lines and lines starting with '#' are skipped. Each shader becomes <output dir>/<symbol>.h,
# defining `static const uint32_t <symbol>[]`. A header is rewritten only when its text changes.

import argparse
import os
import shutil
import subprocess
import sys
import tempfile


def compile_one(dxc, source, profile, entry, out_path, include_dir):
    cmd = [dxc, "-spirv", "-fspv-target-env=vulkan1.3", "-T", profile, "-E", entry, "-O3",
           "-I", include_dir, "-Fo", out_path, source]
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        sys.stderr.write(result.stdout + result.stderr)
        raise SystemExit(f"dxc failed: {source} ({profile} {entry})")


def header_text(symbol, words, source, profile, entry):
    lines = [
        "// Generated by scripts/tooling/rhi/build_spirv.py: do not edit.",
        f"// {os.path.basename(source)}, {profile} {entry}, SPIR-V for Vulkan 1.3",
        "#pragma once",
        "#include <cstdint>",
        f"static const uint32_t {symbol}[] =",
        "{",
    ]
    for i in range(0, len(words), 8):
        lines.append("\t" + ", ".join(f"0x{w:08x}" for w in words[i:i + 8]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dxc", required=True)
    parser.add_argument("--spirv-val", default=shutil.which("spirv-val"))
    parser.add_argument("manifest")
    parser.add_argument("outdir")
    args = parser.parse_args()

    base = os.path.dirname(os.path.abspath(args.manifest))
    os.makedirs(args.outdir, exist_ok=True)
    count = 0
    with open(args.manifest, encoding="utf-8") as f:
        entries = [line.split() for line in f if line.strip() and not line.lstrip().startswith("#")]
    with tempfile.TemporaryDirectory() as tmp:
        for parts in entries:
            if len(parts) != 4:
                raise SystemExit(f"bad manifest line: {' '.join(parts)}")
            source, profile, entry, symbol = parts
            source = os.path.join(base, source)
            spv = os.path.join(tmp, symbol + ".spv")
            compile_one(args.dxc, source, profile, entry, spv, base)
            if args.spirv_val:
                val = subprocess.run([args.spirv_val, "--target-env", "vulkan1.3", spv], capture_output=True, text=True)
                if val.returncode != 0:
                    sys.stderr.write(val.stdout + val.stderr)
                    raise SystemExit(f"spirv-val rejected {symbol}")
            data = open(spv, "rb").read()
            words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
            text = header_text(symbol, words, source, profile, entry)
            out = os.path.join(args.outdir, symbol + ".h")
            if not os.path.exists(out) or open(out, encoding="utf-8").read() != text:
                with open(out, "w", encoding="utf-8", newline="\n") as o:
                    o.write(text)
            count += 1
            print(f"{symbol}: {len(words)} words")
    print(f"{count} shaders")


if __name__ == "__main__":
    main()
