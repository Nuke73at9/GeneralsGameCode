"""Compile the engine's HLSL shaders to Direct3D 9 bytecode headers (Tiberium Project).

  python build_shaders.py [path to fxc.exe]

Uses Microsoft's fxc (Windows SDK). On Linux/macOS it runs fxc.exe under Wine. The generated
*_vs.h / *_ps.h headers are committed, so building the game doesn't need fxc.
"""
import os
import subprocess
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

# (source, entry point, profile, header, array name)
SHADERS = [
    ("sage2object.hlsl", "VSMain", "vs_3_0", "sage2object_vs.h", "Sage2ObjectVertexShader"),
    ("sage2object.hlsl", "PSMain", "ps_3_0", "sage2object_ps.h", "Sage2ObjectPixelShader"),
    ("postprocess.hlsl", "VSMain", "vs_3_0", "postprocess_vs.h", "PostProcessVertexShader"),
    ("postprocess.hlsl", "PSBright", "ps_3_0", "postprocess_bright_ps.h", "PostProcessBrightPixelShader"),
    ("postprocess.hlsl", "PSBlur", "ps_3_0", "postprocess_blur_ps.h", "PostProcessBlurPixelShader"),
    ("postprocess.hlsl", "PSCombine", "ps_3_0", "postprocess_combine_ps.h", "PostProcessCombinePixelShader"),
    ("softparticle.hlsl", "VS_Soft", "vs_3_0", "softparticle_vs.h", "SoftParticleVertexShader"),
    ("softparticle.hlsl", "PS_Soft", "ps_3_0", "softparticle_ps.h", "SoftParticlePixelShader"),
    ("fxaa.hlsl", "PSFXAA", "ps_3_0", "fxaa_ps.h", "FXAAPixelShader"),
    ("fixedfunction.hlsl", "VSMain", "vs_3_0", "fixedfunction_vs.h", "FixedFunctionVertexShader"),
    ("fixedfunction.hlsl", "VSScreen", "vs_3_0", "fixedfunction_screen_vs.h", "FixedFunctionScreenVertexShader"),
    ("fixedfunction.hlsl", "VSTrees", "vs_3_0", "fixedfunction_trees_vs.h", "FixedFunctionTreesVertexShader"),
    ("fixedfunction.hlsl", "PSMain", "ps_3_0", "fixedfunction_ps.h", "FixedFunctionPixelShader"),
    ("fixedfunction.hlsl", "PSModulate", "ps_3_0", "fixedfunction_modulate_ps.h", "FixedFunctionModulatePixelShader"),
    ("fixedfunction.hlsl", "PSDiffuse", "ps_3_0", "fixedfunction_diffuse_ps.h", "FixedFunctionDiffusePixelShader"),
    ("fixedfunction.hlsl", "PSTexture", "ps_3_0", "fixedfunction_texture_ps.h", "FixedFunctionTexturePixelShader"),
    ("ssao.hlsl", "PSSceneDepth", "ps_3_0", "ssao_depth_ps.h", "SSAODepthPixelShader"),
    ("ssao.hlsl", "VSMain", "vs_3_0", "ssao_vs.h", "SSAOVertexShader"),
    ("ssao.hlsl", "PSAO", "ps_3_0", "ssao_ao_ps.h", "SSAOPixelShader"),
    ("ssao.hlsl", "PSBlur", "ps_3_0", "ssao_blur_ps.h", "SSAOBlurPixelShader"),
    ("ssao.hlsl", "PSApply", "ps_3_0", "ssao_apply_ps.h", "SSAOApplyPixelShader"),
]


def fxc_command(fxc):
    if os.name == "nt":
        return [fxc]
    return ["wine", fxc]


def main():
    fxc = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("FXC", "fxc.exe")
    env = dict(os.environ, WINEDEBUG="-all")
    for src, entry, profile, header, name in SHADERS:
        if not os.path.exists(os.path.join(HERE, src)):
            continue
        out = "_build_shaders.cso"  # relative: an absolute Unix path would read as an fxc option under Wine
        cmd = fxc_command(fxc) + ["/nologo", "/O3", "/T", profile, "/E", entry, "/Fo", out, src]
        r = subprocess.run(cmd, cwd=HERE, env=env, capture_output=True, text=True)
        path = os.path.join(HERE, out)
        if r.returncode != 0 or not os.path.exists(path):
            sys.exit(f"{src} {entry}: fxc failed\n{r.stdout}\n{r.stderr}")
        data = open(path, "rb").read()
        os.remove(path)
        tokens = struct.unpack(f"<{len(data) // 4}I", data)
        rows = [", ".join(f"0x{t:08x}" for t in tokens[i:i + 6]) for i in range(0, len(tokens), 6)]
        with open(os.path.join(HERE, header), "w", newline="\n") as f:
            f.write(f"// Generated by build_shaders.py from {src} ({entry}, {profile}); do not edit.\n")
            f.write(f"static const DWORD {name}[] =\n{{\n\t" + ",\n\t".join(rows) + "\n};\n")
        print(f"{header}: {len(tokens)} tokens")


if __name__ == "__main__":
    main()
