"""Tiny Direct3D 9 shader assembler (ps_2_0 subset) for the Tiberium Project.

Turns shader assembly into the DWORD tokens IDirect3DDevice9::CreatePixelShader takes, so the
engine can embed its shaders without the DirectX SDK. Supports what our shaders use:
dcl / dcl_2d, def, texld, texkill, and the plain arithmetic instructions, with write masks,
swizzles, negation and the _sat modifier.

  python d3dasm.py shader.asm out.h ARRAY_NAME   (also writes out.h.bin for checking with a disassembler)
"""
import re
import struct
import sys

OPS = {"nop": 0, "mov": 1, "add": 2, "sub": 3, "mad": 4, "mul": 5, "rcp": 6, "rsq": 7,
       "dp3": 8, "dp4": 9, "min": 10, "max": 11, "exp": 14, "log": 15, "lrp": 18, "frc": 19,
       "pow": 32, "crs": 33, "abs": 35, "nrm": 36, "texkill": 65, "texld": 66, "cmp": 88,
       "dp2add": 90}
NSRC = {"nop": 0, "mov": 1, "add": 2, "sub": 2, "mad": 3, "mul": 2, "rcp": 1, "rsq": 1,
        "dp3": 2, "dp4": 2, "min": 2, "max": 2, "exp": 1, "log": 1, "lrp": 3, "frc": 1,
        "pow": 2, "crs": 2, "abs": 1, "nrm": 1, "texld": 2, "cmp": 3, "dp2add": 3}
REGS = {"r": 0, "v": 1, "c": 2, "t": 3, "oC": 8, "s": 10}
COMP = {"x": 0, "y": 1, "z": 2, "w": 3, "r": 0, "g": 1, "b": 2, "a": 3}


def reg_bits(name):
    m = re.fullmatch(r"(oC|[rvcts])(\d+)", name)
    if not m:
        raise ValueError(f"unknown register {name}")
    t, n = REGS[m.group(1)], int(m.group(2))
    return n | ((t & 7) << 28) | ((t & 0x18) << 8) | 0x80000000


def dst(tok, mods=0):
    name, _, mask = tok.partition(".")
    bits = 0
    for ch in (mask or "xyzw"):
        bits |= 1 << COMP[ch]
    return reg_bits(name) | (bits << 16) | mods


def src(tok):
    neg = tok.startswith("-")
    tok = tok.lstrip("-")
    name, _, sw = tok.partition(".")
    sw = sw or "xyzw"
    sw = (sw + sw[-1] * 4)[:4]
    swz = sum(COMP[ch] << (2 * i) for i, ch in enumerate(sw))
    return reg_bits(name) | (swz << 16) | ((1 << 24) if neg else 0)


def assemble(text):
    out = []
    for raw in text.splitlines():
        line = raw.split(";")[0].strip()
        if not line:
            continue
        op, _, rest = line.partition(" ")
        args = [a.strip() for a in rest.split(",")] if rest.strip() else []
        if op in ("ps_2_0",):
            out.append(0xFFFF0200)
        elif op == "def":
            vals = [float(a) for a in args[1:]]
            out += [0x05000051, dst(args[0])] + [struct.unpack("<I", struct.pack("<f", v))[0] for v in vals]
        elif op in ("dcl", "dcl_2d"):
            usage = 0x80000000 | ((2 << 27) if op == "dcl_2d" else 0)
            out += [0x0200001F, usage, dst(args[0])]
        elif op == "texkill":
            out += [0x01000000 | OPS[op], dst(args[0])]
        else:
            sat = op.endswith("_sat")
            base = op[:-4] if sat else op
            if base not in OPS:
                raise ValueError(f"unknown instruction {op}")
            n = NSRC[base]
            if len(args) != n + 1:
                raise ValueError(f"{op}: expected {n + 1} operands in '{raw.strip()}'")
            out.append(((n + 1) << 24) | OPS[base])
            out.append(dst(args[0], (1 << 20) if sat else 0))
            out += [src(a) for a in args[1:]]
    out.append(0x0000FFFF)
    return out


def main():
    text = open(sys.argv[1]).read()
    tokens = assemble(text)
    with open(sys.argv[2] + ".bin", "wb") as f:
        f.write(struct.pack(f"<{len(tokens)}I", *tokens))
    if len(sys.argv) > 3:
        lines = [", ".join(f"0x{t:08x}" for t in tokens[i:i + 6]) for i in range(0, len(tokens), 6)]
        body = ",\n\t".join(lines)
        with open(sys.argv[2], "w") as f:
            f.write(f"// Generated by d3dasm.py from {sys.argv[1].split('/')[-1]}; do not edit.\n")
            f.write(f"static const DWORD {sys.argv[3]}[] =\n{{\n\t{body}\n}};\n")


if __name__ == "__main__":
    main()
